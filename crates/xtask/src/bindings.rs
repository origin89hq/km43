    #[test]
    fn a_link_tag_is_never_split_across_lines() {
        assert_eq!(
            words_of("Answered by {@link MessageType.HelloResponse}. Since 1.0."),
            [
                "Answered",
                "by",
                "{@link MessageType.HelloResponse}.",
                "Since",
                "1.0."
            ]
        );
        assert!(words_of("  ").is_empty());
    }

    /// `—` is the registry's word for a value that is no quantity, and a scale
    /// of 0 has no formula worth printing.
    #[test]
    fn a_metric_says_its_unit_and_scale_only_where_it_has_them() {
        assert_eq!(
            metric_doc("DC voltage", "V", -3),
            "DC voltage. Unit `V`, `value = raw × 10^-3`."
        );
        assert_eq!(metric_doc("AC energy", "Wh", 0), "AC energy. Unit `Wh`.");
        assert_eq!(
            metric_doc("last boot reason", "—", 0),
            "Last boot reason. No unit."
        );
    }

    /// The sealed column says what a receiver accepts bare. It was once rendered
    /// as *a receiver reads it out of a bare body*, which a client could take
    /// as licence to reject the wrapped form P-142 requires inside a session.
    #[test]
    fn an_error_code_never_says_it_travels_bare() {
        let bare = error_doc("Session expired", false);
        assert!(
            bare.starts_with("Session expired. A receiver may also accept it"),
            "{bare}"
        );
        assert!(bare.contains("(P-142)"), "{bare}");

        let sealed = error_doc("Unknown section", true);
        assert!(
            sealed.contains("discards a bare one carrying it (P-051)"),
            "{sealed}"
        );
        assert!(sealed.contains("(P-142)"), "{sealed}");

        assert!(error_doc("", false).starts_with(". A receiver"));
    }

    /// A reserved number is in the bindings because a peer may send it, and
    /// without the caveat it reads as specified.
    #[test]
    fn a_reserved_row_says_so_and_a_live_one_does_not() {
        assert_eq!(with_caveat("Acted on.", Some(Status::Live)), "Acted on.");
        assert_eq!(with_caveat("pv array", None), "pv array");
        assert_eq!(
            with_caveat("accepted", Some(Status::Reserved)),
            "accepted\n\nReserved: allocated, and not specified yet."
        );
    }

    /// Each half of a message points at the other, and a message with no
    /// request, `Event`, does not claim to answer one.
    #[test]
    fn a_message_links_its_request_and_response() {
        let hello = Message {
            name: "Hello".to_owned(),
            request: Some(crate::registry::Opcode(0x01)),
            response: Some(crate::registry::Opcode(0x81)),
            auth_request: Some(Auth::Handshake),
            auth_response: Some(Auth::Handshake),
            status: Status::Live,
            since: crate::registry::Version { major: 1, minor: 0 },
        };
        let [Some(request), Some(response)] = message_members(&hello) else {
            panic!("Hello has both halves");
        };
        assert!(
            request.doc.contains("{@link MessageType.HelloResponse}"),
            "{}",
            request.doc
        );
        assert!(request.doc.contains("Auth `handshake`"), "{}", request.doc);
        assert!(
            response.doc.contains("{@link MessageType.Hello}"),
            "{}",
            response.doc
        );

        let event = Message {
            name: "Event".to_owned(),
            request: None,
            response: Some(crate::registry::Opcode(0x04)),
            auth_request: None,
            auth_response: Some(Auth::Sealed),
            ..hello
        };
        let [None, Some(only)] = message_members(&event) else {
            panic!("Event is a response with no request");
        };
        assert!(!only.doc.contains("{@link"), "{}", only.doc);
    }
