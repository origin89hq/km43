/// The paragraph every open space's doc ends with.
const OPEN: &str = "Open: a device may emit a value this table does not name, and a client \
                    shows that one carrier as unrecognised rather than blanking the message \
                    around it.";

/// REGISTRY.md, read for the paragraph each space opens with.
struct RegistryDoc(String);

impl RegistryDoc {
    /// Where a relative link in REGISTRY.md points once it is out of the repository.
    const REPOSITORY: &'static str = "https://github.com/origin89hq/km43/blob/main/";

    /// The first paragraph under `heading`, which is where REGISTRY.md says what
    /// a space is before it argues about it.
    ///
    /// A section that opens straight into its table is refused rather than
    /// emitted bare: that is the undocumented export the bindings exist to stop
    /// shipping, and the fix is a sentence in REGISTRY.md that both readers get.
    fn summary(&self, heading: &str) -> Result<String> {
        let mut lines = self
            .0
            .lines()
            .skip_while(|l| *l != heading && !l.starts_with(&format!("{heading} ")));
        lines
            .next()
            .with_context(|| format!("{} has no {heading:?} section", Codegen::PATH))?;
        let paragraph: Vec<&str> = lines
            .skip_while(|l| l.trim().is_empty())
            .take_while(|l| !l.trim().is_empty())
            .collect();
        match paragraph.first() {
            Some(first) if !first.starts_with('|') && !first.starts_with('#') => {
                Ok(Self::absolute_links(&paragraph.join("\n")))
            }
            _ => anyhow::bail!(
                "{heading:?} in {} opens with no paragraph, so the TypeScript export it \
                 generates would ship undocumented. Write the sentence that says what the \
                 space is above its table.",
                Codegen::PATH
            ),
        }
    }

    /// Relative Markdown links, rewritten to the repository: they resolve against
    /// `docs/protocol/` in REGISTRY.md and against nothing in the npm package.
    fn absolute_links(text: &str) -> String {
        let mut out = String::with_capacity(text.len());
        let mut rest = text;
        while let Some(at) = rest.find("](") {
            let (head, tail) = rest.split_at(at + 2);
            out.push_str(head);
            rest = tail;
            if rest.starts_with("http") || rest.starts_with('#') {
                continue;
            }
            out.push_str(Self::REPOSITORY);
            match rest.strip_prefix("../") {
                Some(up) => {
                    out.push_str("docs/");
                    rest = up;
                }
                None => out.push_str("docs/protocol/"),
            }
        }
        out.push_str(rest);
        out
    }
}

/// An open space's summary with the paragraph that says it is open.
fn open(summary: &str) -> String {
    format!("{summary}\n\n{OPEN}")
}

/// One generated space: its type name, what it is, and its members.
///
/// Built once and rendered by both languages. When each emitter took its words
/// from the registry on its own, the TypeScript had them and the Rust had bare
/// numbers, and nothing noticed.
struct Space {
    name: String,
    doc: String,
    members: Vec<Member>,
}

/// One generated constant: its name, its number, and what it means.
struct Member {
    name: String,
    number: u16,
    doc: String,
}

/// The doc of a row with no meaning column: its registry name, as code. Bare,
/// `refused_busy` reads to rustdoc's pedantic lint as an identifier somebody
/// forgot to quote, and to a person as the same.
fn named(name: &str) -> String {
    format!("`{name}`")
}

/// An outcome or enum row's meaning, or its name where it has none.
fn outcome_members(entries: &[crate::registry::Outcome]) -> Vec<Member> {
    entries
        .iter()
        .filter(|e| !e.status.is_gone())
        .map(|e| Member {
            name: variant(&e.name),
            number: u16::from(e.value),
            doc: with_caveat(
                &e.meaning
                    .as_deref()
                    .map_or_else(|| named(&e.name), sentence),
                Some(e.status),
            ),
        })
        .collect()
}

/// A message's request and response constants, each saying how it is
/// authenticated and which constant answers it.
fn message_members(m: &Message) -> [Option<Member>; 2] {
    let name = variant(&m.name);
    let auth =
        |a: Option<Auth>| a.map_or_else(String::new, |a| format!(" Auth `{a}`. {}", a.summary()));
    let tail = format!(" Since {}.", m.since);
    let request = m.request.map(|r| {
        let answered = m.response.map_or_else(String::new, |_| {
            format!(" Answered by {{@link MessageType.{name}Response}}.")
        });
        Member {
            name: name.clone(),
            number: r.0,
            doc: with_caveat(
                &format!(
                    "The `{}` request.{}{answered}{tail}",
                    m.name,
                    auth(m.auth_request)
                ),
                Some(m.status),
            ),
        }
    });
    let response = m.response.map(|r| {
        let what = if m.request.is_some() {
            format!("The answer to {{@link MessageType.{name}}}.")
        } else {
            format!("The `{}` message.", m.name)
        };
        Member {
            name: format!("{name}Response"),
            number: r.0,
            doc: with_caveat(
                &format!("{what}{}{tail}", auth(m.auth_response)),
                Some(m.status),
            ),
        }
    });
    [request, response]
}

/// An error code's meaning and what the sealed column says about it.
///
/// The column is the receiver's check, never the sender's: P-142 wraps an
/// `Error` whenever the sender holds a session, whatever the code. Reading it
/// as *this code travels bare* would tell a client to reject a valid wrapped
/// error, or a controller to send an unauthenticated one inside a session.
fn error_doc(meaning: &str, sealed: bool) -> String {
    let rule = if sealed {
        "A receiver accepts it only inside a sealed body, and discards a bare one \
         carrying it (P-051)."
    } else {
        "A receiver may also accept it from a bare body."
    };
    format!(
        "{} {rule} Whether it arrives sealed is decided by whether the sender holds \
         a session, not by the code (P-142).",
        sentence(meaning)
    )
}

/// What a metric kind is read in. `—` is the registry's word for a value that
/// is not a quantity, such as a state drawn from an enum space.
fn metric_doc(name: &str, unit: &str, scale: i8) -> String {
    let name = sentence(&capital(name));
    match (unit, scale) {
        ("—", _) => format!("{name} No unit."),
        (unit, 0) => format!("{name} Unit `{unit}`."),
        (unit, scale) => format!("{name} Unit `{unit}`, `value = raw × 10^{scale}`."),
    }
}

/// A row's text with its status caveat as a second paragraph, when it has one.
fn with_caveat(text: &str, status: Option<Status>) -> String {
    match status.and_then(Status::caveat) {
        Some(caveat) => format!("{text}\n\n{caveat}"),
        None => text.to_owned(),
    }
}

/// Registry text as a sentence. `meaning` columns are written as table cells,
/// without a closing full stop.
fn sentence(text: &str) -> String {
    let text = text.trim_end();
    if text.ends_with('.') {
        text.to_owned()
    } else {
        format!("{text}.")
    }
}

fn capital(text: &str) -> String {
    let mut c = text.chars();
    c.next().map_or_else(String::new, |f| {
        f.to_uppercase().collect::<String>() + c.as_str()
    })
}

/// A `/** */` comment, wrapped to 80 columns, one paragraph per blank line.
///
/// Registry text can carry a `*/`, which would end the comment and hand the
/// rest of the row to the compiler, and an `@`, which `TSDoc` reads as a tag.
/// Both are escaped; the generator's own `{@link}` is put back.
fn ts_doc(o: &mut String, indent: &str, text: &str) {
    let text = text
        .replace("*/", "*\\/")
        .replace('@', "\\@")
        .replace("{\\@link ", "{@link ");
    let width = 80usize.saturating_sub(indent.len() + 3);
    let paragraphs = wrap(&text, width);
    if let [only] = paragraphs.as_slice()
        && let [line] = only.as_slice()
        && columns(line) + 4 <= width
    {
        let _ = writeln!(o, "{indent}/** {line} */");
        return;
    }
    let _ = writeln!(o, "{indent}/**");
    for (n, lines) in paragraphs.iter().enumerate() {
        if n > 0 {
            let _ = writeln!(o, "{indent} *");
        }
        for line in lines {
            let _ = writeln!(o, "{indent} * {line}");
        }
    }
    let _ = writeln!(o, "{indent} */");
}

/// A `///` comment, wrapped to 80 columns, one paragraph per blank line.
///
/// Each line carries its own `///`, so a newline in registry text cannot hand
/// the rest of the row to the compiler the way `*/` could in TypeScript. What
/// it can do is be read as rustdoc markup; [`rust_markdown`] disarms that.
/// Empty text writes nothing, so `missing_docs` sees the gap.
fn rust_doc(o: &mut String, indent: &str, text: &str) {
    let width = 80usize.saturating_sub(indent.len() + 4);
    for (n, lines) in wrap(&rust_markdown(text), width).iter().enumerate() {
        if n > 0 {
            let _ = writeln!(o, "{indent}///");
        }
        for line in lines {
            let _ = writeln!(o, "{indent}/// {line}");
        }
    }
}

/// Registry text as rustdoc Markdown.
///
/// Rustdoc reads a stray `[word]` as an intra-doc link and `<word>` as an HTML
/// tag, and under `-D warnings` a broken one of either fails `just doc`, so
/// both are escaped outside code spans; a Markdown link is kept. The
/// generator's own `{@link A.B}` becomes the rustdoc link ``[`A::B`]``.
fn rust_markdown(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut code = false;
    let mut rest = text;
    while let Some(c) = rest.chars().next() {
        let after = rest.get(c.len_utf8()..).unwrap_or_default();
        match c {
            '`' => code = !code,
            '{' if !code && rest.starts_with("{@link ") => {
                if let Some((target, tail)) =
                    after.strip_prefix("@link ").and_then(|t| t.split_once('}'))
                {
                    let _ = write!(out, "[`{}`]", target.replace('.', "::"));
                    rest = tail;
                    continue;
                }
            }
            '[' if !code => {
                if let Some(end) = markdown_link_end(rest) {
                    let (link, tail) = rest.split_at(end);
                    out.push_str(link);
                    rest = tail;
                    continue;
                }
                out.push('\\');
            }
            ']' | '<' | '>' if !code => out.push('\\'),
            _ => {}
        }
        out.push(c);
        rest = after;
    }
    out
}

/// The byte length of the Markdown link `text` opens with, if it opens with one.
fn markdown_link_end(text: &str) -> Option<usize> {
    let close = text.find("](")?;
    let label = text.get(1..close)?;
    if label.contains(['[', ']', '\n']) {
        return None;
    }
    let url = text.get(close + 2..)?;
    let end = url.find(')')?;
    if url.get(..end)?.contains(char::is_whitespace) {
        return None;
    }
    Some(close + 2 + end + 1)
}

/// Text in paragraphs of lines no wider than `width`, split on blank lines.
fn wrap(text: &str, width: usize) -> Vec<Vec<String>> {
    text.split("\n\n")
        .map(|p| {
            let mut lines: Vec<String> = Vec::new();
            for word in words_of(p) {
                match lines.last_mut() {
                    Some(line) if columns(line) + 1 + columns(&word) <= width => {
                        line.push(' ');
                        line.push_str(&word);
                    }
                    _ => lines.push(word),
                }
            }
            lines
        })
        .filter(|lines| !lines.is_empty())
        .collect()
}

/// A closed space: an unknown value is a parse error, never a fallback.
fn closed_enum(o: &mut String, repr: &str, space: &Space) {
    if space.members.is_empty() {
        return;
    }
    let name = &space.name;
    rust_doc(o, "", &space.doc);
    let _ = writeln!(o, "#[derive(Debug, Clone, Copy, PartialEq, Eq)]");
    let _ = writeln!(
        o,
        r#"#[cfg_attr(feature = "defmt", derive(defmt::Format))]"#
    );
    let _ = writeln!(o, "#[repr({repr})]");
    let _ = writeln!(o, "pub enum {name} {{");
    for m in &space.members {
        rust_doc(o, "    ", &m.doc);
        let _ = writeln!(o, "    {} = {:#x},", m.name, m.number);
    }
    let _ = writeln!(o, "}}\n");
    let _ = writeln!(o, "impl TryFrom<{repr}> for {name} {{");
    let _ = writeln!(o, "    type Error = ();\n");
    let _ = writeln!(
        o,
        "    fn try_from(v: {repr}) -> Result<Self, Self::Error> {{"
    );
    let _ = writeln!(o, "        match v {{");
    for m in &space.members {
        let _ = writeln!(o, "            {:#x} => Ok(Self::{}),", m.number, m.name);
    }
    let _ = writeln!(o, "            _ => Err(()),\n        }}\n    }}\n}}\n");
}

/// An open space: the value is carried whether or not it is named.
fn open_newtype(o: &mut String, space: &Space, open: bool) {
    if !open {
        return;
    }
    let name = &space.name;
    rust_doc(o, "", &space.doc);
    let _ = writeln!(o, "#[derive(Debug, Clone, Copy, PartialEq, Eq)]");
    let _ = writeln!(
        o,
        r#"#[cfg_attr(feature = "defmt", derive(defmt::Format))]"#
    );
    let _ = writeln!(o, "pub struct {name}(pub u16);\n");
    let _ = writeln!(o, "impl {name} {{");
    for m in &space.members {
        rust_doc(o, "    ", &m.doc);
        let _ = writeln!(
            o,
            "    pub const {}: Self = Self({:#06x});",
            m.name, m.number
        );
    }
    let _ = writeln!(o, "}}\n");
}

fn ts_enum(o: &mut String, space: &Space) {
    if space.members.is_empty() {
        return;
    }
    ts_doc(o, "", &space.doc);
    let _ = writeln!(o, "export enum {} {{", space.name);
    for m in &space.members {
        ts_doc(o, "  ", &m.doc);
        let _ = writeln!(o, "  {} = {:#x},", m.name, m.number);
    }
    let _ = writeln!(o, "}}\n");
}

fn ts_const_map(o: &mut String, space: &Space) {
    ts_doc(o, "", &space.doc);
    let _ = writeln!(o, "export const {} = {{", space.name);
    for m in &space.members {
        ts_doc(o, "  ", &m.doc);
        let _ = writeln!(o, "  {}: {:#06x},", m.name, m.number);
    }
    let _ = writeln!(o, "}} as const;\n");
}

/// The words a doc comment wraps between. `{@link X}` is one: `TSDoc` reads an
/// inline tag split across two lines, but a reader grepping for it does not.
fn words_of(paragraph: &str) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    for word in paragraph.split_whitespace() {
        match out.last_mut() {
            Some(last) if last.ends_with("{@link") => {
                last.push(' ');
                last.push_str(word);
            }
            _ => out.push(word.to_owned()),
        }
    }
    out
}

/// Width as a reader sees it: `—` is three bytes and one column.
fn columns(text: &str) -> usize {
    text.chars().count()
}

/// `battery voltage` becomes `BatteryVoltage`, which is what a Rust variant and
/// a TypeScript member both want.
///
/// A parenthetical is a note rather than part of the name — `battery current
/// (+ charge, − discharge)` is `BatteryCurrent` — and everything that is not a
/// letter or a digit is a separator.
fn variant(s: &str) -> String {
    words(s)
        .map(|w| {
            // Only the first letter is touched: `ReadLog` is already the name
            // somebody wrote, and lowercasing the rest gives `Readlog`.
            let mut c = w.chars();
            c.next().map_or_else(String::new, |f| {
                f.to_ascii_uppercase().to_string() + c.as_str()
            })
        })
        .collect()
}

/// The same name as a constant: `battery voltage` becomes `BATTERY_VOLTAGE`.
fn screaming(s: &str) -> String {
    words(s)
        .map(str::to_ascii_uppercase)
        .collect::<Vec<_>>()
        .join("_")
}

fn words(s: &str) -> impl Iterator<Item = &str> {
    s.split_once('(')
        .map_or(s, |(before, _)| before)
        .split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|w| !w.is_empty())
}

/// A JavaScript string literal for `s`: a JSON string is one, with quotes,
/// backslashes and control characters escaped.
fn js(s: &str) -> String {
    serde_json::to_string(s).unwrap_or_else(|_| "\"\"".to_owned())
}

/// A mask in binary, `width` digits wide and grouped in fours from the right,
/// the way clippy's `unreadable_literal` wants a literal of five digits or more.
fn nibbles(mask: u16, width: usize) -> String {
    let digits = format!("{mask:0width$b}");
    let mut out = String::with_capacity(digits.len() + digits.len() / 4);
    for (index, digit) in digits.chars().enumerate() {
        if index > 0 && (digits.len() - index) % 4 == 0 {
            out.push('_');
        }
        out.push(digit);
    }
    out
}

